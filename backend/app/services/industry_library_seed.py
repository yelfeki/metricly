# ---------------------------------------------------------------------------
# Seed function
# ---------------------------------------------------------------------------

async def seed_industry_library(session: AsyncSession) -> None:
    """Idempotent seed: inserts industries, instruments, and mappings."""

    # ── 1. Seed industries ──────────────────────────────────────────────────
    for ind_data in _INDUSTRIES:
        existing = (
            await session.execute(
                select(Industry).where(Industry.slug == ind_data["slug"])
            )
        ).scalar_one_or_none()
        if existing:
            continue
        industry = Industry(
            name=ind_data["name"],
            slug=ind_data["slug"],
            description=ind_data.get("description"),
            keywords=ind_data.get("keywords"),
            icon_name=ind_data.get("icon_name"),
            color_hex=ind_data.get("color_hex"),
            order_index=ind_data.get("order_index", 0),
        )
        session.add(industry)

    await session.flush()

    # ── 2. Seed instruments & mappings ──────────────────────────────────────
    for inst_data in _ALL_INDUSTRY_INSTRUMENTS:
        # Idempotent by short_name
        existing_inst = (
            await session.execute(
                select(Instrument).where(Instrument.short_name == inst_data["short_name"])
            )
        ).scalar_one_or_none()

        if existing_inst is None:
            import json as _json

            instrument = Instrument(
                name=inst_data["name"],
                short_name=inst_data["short_name"],
                description=inst_data.get("description"),
                construct_measured=inst_data.get("construct_measured"),
                theoretical_framework=inst_data.get("theoretical_framework"),
                source_citation=inst_data.get("source_citation"),
                license_type=inst_data.get("license_type", "open"),
                is_proprietary=inst_data.get("is_proprietary", False),
                total_items=inst_data.get("total_items", 0),
                estimated_minutes=inst_data.get("estimated_minutes"),
                scoring_type=inst_data.get("scoring_type", "mean"),
                response_format=inst_data.get("response_format", "likert5"),
                validated_populations=inst_data.get("validated_populations"),
                languages=inst_data.get("languages"),
                reliability_alpha=inst_data.get("reliability_alpha"),
                industry_tags=_json.dumps(inst_data.get("industry_tags_list", [])),
                is_industry_specific=True,
            )
            session.add(instrument)
            await session.flush()

            # Subscales
            subscale_map: dict[str, InstrumentSubscale] = {}
            for sub_data in inst_data.get("subscales", []):
                subscale = InstrumentSubscale(
                    instrument_id=instrument.id,
                    name=sub_data["name"],
                    description=sub_data.get("description"),
                    item_count=sub_data.get("item_count", 0),
                    scoring_notes=sub_data.get("scoring_notes"),
                )
                session.add(subscale)
                await session.flush()
                subscale_map[sub_data["name"]] = subscale

            # Items
            for idx, item in enumerate(inst_data.get("items", [])):
                sub_obj = subscale_map.get(item.get("subscale") or "")
                session.add(InstrumentItem(
                    instrument_id=instrument.id,
                    subscale_id=sub_obj.id if sub_obj else None,
                    item_text=item["text"],
                    order_index=idx,
                    is_reverse_scored=item.get("reverse", False),
                ))

            existing_inst = instrument

        # ── 3. Create industry mappings ──────────────────────────────────────
        for slug, short_names in _INDUSTRY_INSTRUMENT_MAP.items():
            if inst_data["short_name"] not in short_names:
                continue

            industry_obj = (
                await session.execute(
                    select(Industry).where(Industry.slug == slug)
                )
            ).scalar_one_or_none()
            if industry_obj is None:
                continue

            already_mapped = (
                await session.execute(
                    select(IndustryInstrumentMapping).where(
                        IndustryInstrumentMapping.industry_id == industry_obj.id,
                        IndustryInstrumentMapping.instrument_id == existing_inst.id,
                    )
                )
            ).scalar_one_or_none()

            if already_mapped is None:
                session.add(IndustryInstrumentMapping(
                    industry_id=industry_obj.id,
                    instrument_id=existing_inst.id,
                    relevance_score=inst_data.get("relevance_score", 3),
                    use_case_note=inst_data.get("use_case_note"),
                ))

    await session.commit()
    log.info(
        "Industry library seed complete: %d industries, %d instruments",
        len(_INDUSTRIES),
        len(_ALL_INDUSTRY_INSTRUMENTS),
    )
