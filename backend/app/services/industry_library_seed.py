# Helper: build item list with optional subscale tagging
# ---------------------------------------------------------------------------

def _items(texts: list[tuple[str, bool, str | None]]) -> list[dict]:
    """texts: list of (item_text, is_reverse_scored, subscale_name_or_None)."""
    return [{"text": t, "reverse": r, "subscale": s} for t, r, s in texts]


